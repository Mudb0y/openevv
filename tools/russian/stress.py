#!/usr/bin/env python3
"""Write the table eci_russian.c looks Russian stress up in.

Two lists go in. tools/russian/stress.txt is ours: a word to a line with its
stressed vowel written as a capital, for the words heard wrong and the ones
too common to leave to anything else, and it wins. tools/russian/
openrussian.tsv.gz is OpenRussian's dictionary, every inflected form of every
word it has with the vowel its stress is on, which openrussian.py makes and
NOTICE says the licence of.

And a third comes out of the second: a word written with ё is very often
typed with е, so еще and идет are put in as well, wherever the е spelling is
not a word of its own, with a mark saying the stressed е is to be read as ё.

What is written is eci_russian_stress.h, and it is half a million words, so
it is packed: a letter is a byte, the words are sorted and each is written as
how much of the one before it it shares and the rest, and every thirty-second
starts afresh, so the engine can find a block by halves and read on from
there. About two megabytes.

A line of stress.txt that marks no vowel, marks more than one, marks a
consonant, or has a space or hyphen in it is reported and left out.

usage: stress.py [--check] [--out FILE]
"""

import argparse
import gzip
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OURS = os.path.join(HERE, "stress.txt")
THEIRS = os.path.join(HERE, "openrussian.tsv.gz")
TARGET = os.path.join(HERE, "..", "..", "src", "eci", "synth", "eci_russian_stress.h")

VOWELS = "аеёиоуыэюя"
#: The order the engine numbers letters in, from one. eci_russian.c's
#: letterCode says the same.
LETTERS = "абвгдеёжзийклмнопрстуфхцчшщъыьэюя"
YO_FLAG = 0x80
BLOCK = 32


def ours():
    entries = {}
    problems = []
    for number, raw in enumerate(open(OURS, encoding="utf-8"), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if " " in line or "-" in line:
            problems.append("%d: %s has a space or hyphen in it" % (number, line))
            continue
        capitals = [i for i, c in enumerate(line) if c.isupper()]
        word = line.lower()
        if any(c not in LETTERS for c in word):
            problems.append("%d: %s is not all Cyrillic" % (number, line))
            continue
        vowels = [i for i, c in enumerate(word) if c in VOWELS]
        if len(vowels) < 2:
            continue
        if len(capitals) > 1 or any(line[i].lower() not in VOWELS for i in capitals):
            problems.append("%d: %s marks something other than one vowel" % (number, line))
            continue
        if capitals:
            at = capitals[0]
        elif "ё" in word:
            at = word.index("ё")
        else:
            problems.append("%d: %s marks no stress" % (number, line))
            continue
        stress = vowels.index(at)
        if word in entries and entries[word] != stress:
            problems.append("%d: %s disagrees with an earlier line, which is kept" % (number, line))
            continue
        entries[word] = stress
    return entries, problems


def theirs():
    entries = {}
    if not os.path.isfile(THEIRS):
        return entries
    with gzip.open(THEIRS, "rt", encoding="utf-8") as f:
        for line in f:
            word, vowel = line.rstrip("\n").split("\t")
            entries[word] = int(vowel)
    return entries


def with_yo_typed_as_e(entries):
    """Every word with ё in it a second time with е, marked."""
    out = dict(entries)
    for word, stress in entries.items():
        if word.count("ё") != 1:
            continue
        plain = word.replace("ё", "е")
        vowels = [i for i, c in enumerate(word) if c in VOWELS]
        # Only when the ё is the stressed vowel, which it nearly always is;
        # an е spelling that is a word of its own is that word.
        if vowels[stress] == word.index("ё") and plain not in out:
            out[plain] = stress | YO_FLAG
    return out


def code(word):
    return bytes(LETTERS.index(c) + 1 for c in word)


def pack(entries):
    rows = sorted((code(w), s) for w, s in entries.items())
    blob = bytearray()
    blocks = []
    previous = b""
    for n, (word, stress) in enumerate(rows):
        if len(word) > 255:
            continue
        if n % BLOCK == 0:
            blocks.append(len(blob))
            shared = 0
        else:
            shared = 0
            while shared < min(len(word), len(previous), 255) and word[shared] == previous[shared]:
                shared += 1
        rest = word[shared:]
        blob += bytes([shared, len(rest)]) + rest + bytes([stress])
        previous = word
    return bytes(blob), blocks, len(rows)


def write(blob, blocks, count, target):
    out = [
        "/* Generated by tools/russian/stress.py. Do not edit.",
        "",
        "   Where the stress of a Russian word falls, for eci_russian.c. Out of",
        "   tools/russian/stress.txt, which is ours, and tools/russian/",
        "   openrussian.tsv.gz, which is OpenRussian's dictionary",
        "   (https://en.openrussian.org) and is under the Creative Commons",
        "   Attribution-ShareAlike 4.0 licence, as this table therefore is too;",
        "   tools/russian/NOTICE says so.",
        "",
        "   %d words. A letter is a byte, numbered from one in the order" % count,
        "   абвгдеёжзийклмнопрстуфхцчшщъыьэюя. The words are sorted, and each is",
        "   how many letters it shares with the word before, how many follow,",
        "   those letters, and the vowel the stress is on counting from nought,",
        "   with 0x80 added when that vowel is an е to be read as ё. Every",
        "   %dth word starts a block and shares nothing. */" % BLOCK,
        "",
        "#define RU_STRESS_BLOCK %d" % BLOCK,
        "#define RU_STRESS_COUNT %d" % count,
        "",
        "static const unsigned int RU_STRESS_BLOCKS[] = {",
    ]
    for i in range(0, len(blocks), 12):
        out.append("    " + ", ".join(str(b) for b in blocks[i : i + 12]) + ",")
    out.append("};")
    out.append("")
    out.append("static const unsigned char RU_STRESS_DATA[] = {")
    for i in range(0, len(blob), 32):
        out.append("    " + ",".join(str(b) for b in blob[i : i + 32]) + ",")
    out.append("};")
    out.append("")
    text = "\n".join(out)
    # Left alone when it already says this, so that a build which runs this
    # every time does not recompile the engine's Russian every time.
    if os.path.isfile(target) and open(target, encoding="utf-8").read() == text:
        return False
    with open(target, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return True


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--out", default=TARGET)
    args = ap.parse_args()

    mine, problems = ours()
    for p in problems:
        sys.stderr.write("stress: line " + p + "\n")
    if args.check:
        return 0
    entries = theirs()
    entries.update(mine)
    entries = with_yo_typed_as_e(entries)
    blob, blocks, count = pack(entries)
    if write(blob, blocks, count, args.out):
        print("stress: %d words, %d bytes packed, into %s"
              % (count, len(blob), args.out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
